#!/usr/bin/env bash
# Update-time migrations for the airplanes.live feed scripts. Sourced by
# update.sh after the cloned tree is available at $GIT.
#
# Each function is:
#   - idempotent: safe to call repeatedly; no-op when already applied,
#   - takes paths and values as explicit arguments (it does not read or
#     mutate update.sh's config-state globals like USER, TARGET, MLAT_*),
#   - does not `source` legacy config files (which would execute arbitrary
#     user-supplied shell content).
#
# install-update-common.sh helpers (airplanes_path, airplanes_is_build_mode)
# are reused as utilities; that file is always sourced before this one.
#
# Phase entry points called from update.sh, in order:
#   run_pre_config_legacy_retirements
#   prepare_legacy_feed_env_migration
#   run_config_file_migrations
#   prune_installed_script_artifacts (called twice; arrays declared at the
#       call site to keep locality with the wildcard cp install)
#   run_post_update_legacy_cleanup
#   finalize_legacy_feed_env_migration

# ---------------------------------------------------------------------------
# Pre-config legacy retirements
# ---------------------------------------------------------------------------

# Retire the orphan airplanes-mlat2 unit left behind by the now-removed
# scripts/second-mlat.sh helper. The unit file lived at the host's
# /lib/systemd/system path; wants symlinks may also exist under
# default.target.wants/ and multi-user.target.wants/. systemctl is only
# invoked when operating on the real system (not under AIRPLANES_ROOT
# redirection, not in build mode); the file removal always runs so the
# rootfs is clean even in chroot/build contexts.
migrate_retire_airplanes_mlat2_unit() {
    local mlat2_unit mlat2_wants_default mlat2_wants_multi
    mlat2_unit="$(airplanes_path /lib/systemd/system/airplanes-mlat2.service)"
    mlat2_wants_default="$(airplanes_path /etc/systemd/system/default.target.wants/airplanes-mlat2.service)"
    mlat2_wants_multi="$(airplanes_path /etc/systemd/system/multi-user.target.wants/airplanes-mlat2.service)"
    if [[ -e "$mlat2_unit" || -L "$mlat2_unit" \
        || -L "$mlat2_wants_default" || -L "$mlat2_wants_multi" ]]; then
        echo "Removing legacy airplanes-mlat2 helper unit (was generated by the now-removed second-mlat.sh)" >&2
        if ! airplanes_is_build_mode && [[ "${AIRPLANES_ROOT:-/}" == "/" ]]; then
            systemctl disable --now airplanes-mlat2 2>/dev/null || true
        fi
        rm -f "$mlat2_unit" "$mlat2_wants_default" "$mlat2_wants_multi"
    fi
}

run_pre_config_legacy_retirements() {
    migrate_retire_airplanes_mlat2_unit
}

# ---------------------------------------------------------------------------
# Legacy feed.env preparation
# ---------------------------------------------------------------------------

# Copy the legacy feed-env source into /etc/airplanes/feed.env so the new
# daemons (which read feed.env) inherit the existing config.
#
# Three legacy shapes are recognized:
#   1. Regular file at $legacy_feed_env (standalone install) — copied directly.
#   2. Symlink that already points at $feed_env — no-op (already migrated).
#   3. Symlink that points elsewhere (e.g. legacy ImageBuilder where
#      /etc/default/airplanes -> /boot/airplanes-env) — followed; the
#      target is copied into feed.env so daemons don't get stranded after
#      finalize_legacy_feed_env_migration rewires the symlink.
#
# Subsequent updates are idempotent: once finalize_legacy_feed_env_migration
# has rewired the legacy path to point at feed.env, case 2 fires and the
# function does nothing.
prepare_legacy_feed_env_migration() {
    local legacy_feed_env="$1"
    local feed_env="$2"
    local etc_airplanes="$3"
    mkdir -p "$etc_airplanes"

    if [[ -L "$legacy_feed_env" ]]; then
        local target feed_env_canonical
        target="$(readlink -f "$legacy_feed_env" 2>/dev/null || true)"
        feed_env_canonical="$(readlink -f "$feed_env" 2>/dev/null || printf '%s' "$feed_env")"
        if [[ -n "$target" && "$target" == "$feed_env_canonical" ]]; then
            return 0
        fi
        # Symlink to legacy boot config or similar — copy through to feed.env
        # only when feed.env doesn't already exist, so we don't clobber
        # config that's already been migrated and edited.
        if [[ -n "$target" && -f "$target" && ! -f "$feed_env" ]]; then
            cp -fp "$target" "$feed_env"
        fi
        return 0
    fi

    if [[ -f "$legacy_feed_env" ]]; then
        cp -fp "$legacy_feed_env" "$feed_env"
    fi
}

